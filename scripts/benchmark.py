"""
Measure model loading, inference and (optionally) device start-up times.

    python scripts/benchmark.py                 # models only, synthetic inputs
    python scripts/benchmark.py --hardware      # also opens camera and microphone

Results are printed and written to benchmarks/results/ (git-ignored).
No audio or video is saved; camera frames are discarded immediately and
the speech sample is generated by the Windows speech synthesiser.
"""

from __future__ import annotations

import argparse
import json
import platform
import statistics
import subprocess
import sys
import tempfile
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import numpy as np  # noqa: E402

COLD_SNIPPETS = {
    "backend_import (new, lazy)": "import backend.services.interview_service",
    "face_mesh": "from backend.core.models import get_registry; get_registry().get('face_mesh')",
    "emotion": "from backend.core.models import get_registry; get_registry().get('emotion')",
    "whisper": "from backend.core.models import get_registry; get_registry().get('whisper')",
    "yamnet": "from backend.core.models import get_registry; get_registry().get('yamnet')",
    "sentence": "from backend.core.models import get_registry; get_registry().get('sentence')",
}

SPOKEN = ("Overfitting happens when a model learns the training data too closely and does "
          "not generalize to new data. Regularization and cross validation help to prevent it.")


def cold_load(snippet: str) -> float:
    code = ("import time, sys; sys.path.insert(0, r'%s'); t = time.perf_counter(); %s; "
            "print('ELAPSED', time.perf_counter() - t)") % (ROOT, snippet)
    out = subprocess.run([sys.executable, "-c", code], capture_output=True, text=True, cwd=ROOT)
    for line in out.stdout.splitlines():
        if line.startswith("ELAPSED"):
            return float(line.split()[1])
    raise RuntimeError(out.stderr[-500:])


def timeit(fn, runs: int, warmup: int = 2) -> dict:
    for _ in range(warmup):
        fn()
    samples = []
    for _ in range(runs):
        t = time.perf_counter()
        fn()
        samples.append((time.perf_counter() - t) * 1000)
    return {"mean_ms": statistics.mean(samples), "median_ms": statistics.median(samples),
            "max_ms": max(samples), "runs": runs}


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--hardware", action="store_true")
    parser.add_argument("--skip-cold", action="store_true")
    args = parser.parse_args()

    results: dict = {"python": platform.python_version(), "platform": platform.platform(),
                     "time": time.strftime("%Y-%m-%d %H:%M:%S")}

    if not args.skip_cold:
        print("Cold loads (fresh process each)…")
        results["cold_load_s"] = {}
        for name, snippet in COLD_SNIPPETS.items():
            results["cold_load_s"][name] = cold_load(snippet)
            print(f"  {name:<28} {results['cold_load_s'][name]:7.1f} s")

    from backend.core.models import get_registry
    from backend.vision.emotion_detector import preprocess

    reg = get_registry()
    t = time.perf_counter()
    for name in reg.names:
        reg.get(name)
    results["warm_load_all_in_process_s"] = time.perf_counter() - t

    try:
        import psutil

        results["rss_mb_after_models"] = psutil.Process().memory_info().rss / 1e6
    except ImportError:
        pass

    # ---- vision inference (synthetic frame; no face, so landmark time is a lower bound) ----
    frame = np.random.default_rng(0).integers(0, 255, (480, 640, 3), dtype=np.uint8)
    bbox = (200, 100, 440, 380)
    model = reg.get("emotion")
    batch = preprocess(frame, bbox)
    results["emotion_model_predict_ms"] = timeit(lambda: model.predict(batch, verbose=0), 20)
    results["emotion_model_direct_call_ms"] = timeit(lambda: model(batch, training=False), 20)
    landmarker = reg.get("face_mesh")
    results["face_landmarks_blank_frame_ms"] = timeit(lambda: landmarker.detect(frame), 30)

    # ---- speech ----
    sys.path.insert(0, str(ROOT / "tests"))
    from integration.tts import synthesize, word_error_rate

    with tempfile.TemporaryDirectory() as tmp:
        wav = Path(tmp) / "speech.wav"
        audio = synthesize(SPOKEN, wav)
        if audio is not None:
            whisper_model = reg.get("whisper")
            waveform = audio.astype(np.float32) / 32768.0
            t = time.perf_counter()
            out = whisper_model.transcribe(waveform, fp16=False, language="en")
            results["whisper_in_memory_s"] = time.perf_counter() - t
            results["whisper_in_memory_wer"] = word_error_rate(SPOKEN, out["text"])
            results["speech_seconds"] = audio.size / 16000
            t = time.perf_counter()
            try:
                whisper_model.transcribe(str(wav))  # the original file-based call
                results["whisper_file_based_s"] = time.perf_counter() - t
            except Exception as exc:  # noqa: BLE001
                results["whisper_file_based_error"] = f"{type(exc).__name__}: {exc}"
            yam, _labels = reg.get("yamnet")
            results["yamnet_ms"] = timeit(lambda: yam(waveform), 5, warmup=1)
        else:
            results["speech"] = "Speech synthesis unavailable; speech timings skipped."

    from backend.ai import question_bank as qb
    from backend.ai.answer_evaluator import AnswerEvaluator

    q = qb.get_question("Machine Learning Engineer", 2)
    ev = AnswerEvaluator(lambda: reg.get("sentence"))
    results["answer_evaluation_ms"] = timeit(lambda: ev.evaluate(q, SPOKEN), 10)

    # ---- hardware (optional) ----
    if args.hardware:
        from backend.audio.recorder import MicrophoneRecorder
        from backend.vision.capture import OpenCVCamera

        cam = OpenCVCamera(0)
        t = time.perf_counter()
        try:
            cam.open()
            results["camera_open_s"] = time.perf_counter() - t
            t = time.perf_counter()
            ok, _ = cam.read()
            results["camera_first_frame_s"] = time.perf_counter() - t
            n, t = 0, time.perf_counter()
            while time.perf_counter() - t < 2.0:
                ok, _ = cam.read()  # frames are discarded
                n += bool(ok)
            results["camera_fps"] = n / (time.perf_counter() - t)
        except Exception as exc:  # noqa: BLE001
            results["camera_error"] = str(exc)
        finally:
            cam.release()
        mic = MicrophoneRecorder()
        t = time.perf_counter()
        try:
            mic.open()
            results["microphone_open_s"] = time.perf_counter() - t
        except Exception as exc:  # noqa: BLE001
            results["microphone_error"] = str(exc)
        finally:
            mic.close()

    out_dir = ROOT / "benchmarks" / "results"
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / f"benchmark-{time.strftime('%Y%m%d-%H%M%S')}.json"
    path.write_text(json.dumps(results, indent=2), encoding="utf-8")
    print(json.dumps(results, indent=2))
    print(f"\nSaved to {path}")


if __name__ == "__main__":
    main()
